-- 1. Buat Tabel Produk (products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'Pistol',
    caliber TEXT DEFAULT '9mm',
    price NUMERIC NOT NULL DEFAULT 0,
    description TEXT DEFAULT '',
    specs TEXT[] DEFAULT ARRAY[]::TEXT[],
    image_url TEXT DEFAULT '/guns/pistol.svg',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- 2. Buat Tabel Favorit (favorites)
CREATE TABLE IF NOT EXISTS public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    UNIQUE(user_id, product_id)
);

-- 3. Buat Tabel Ulasan (reviews)
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- ============================================================================
-- Hak Akses Skema & Tabel (PENTING untuk mengatasi error: "permission denied for table products")
-- Memberi izin penuh kepada role `anon` dan `authenticated` untuk operasi CRUD
-- ============================================================================

GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.products TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.favorites TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.reviews TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;

-- ============================================================================
-- Konfigurasi Row Level Security (RLS) & Akses Publik Anon
-- Agar aplikasi PWA dapat melakukan operasi CRUD menggunakan Anon/Publishable Key
-- ============================================================================

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

-- Policy untuk Tabel products (Full Access untuk anon & authenticated)
DROP POLICY IF EXISTS "Public full access for products" ON public.products;
CREATE POLICY "Public full access for products" ON public.products
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Policy untuk Tabel favorites
DROP POLICY IF EXISTS "Public full access for favorites" ON public.favorites;
CREATE POLICY "Public full access for favorites" ON public.favorites
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Policy untuk Tabel reviews
DROP POLICY IF EXISTS "Public full access for reviews" ON public.reviews;
CREATE POLICY "Public full access for reviews" ON public.reviews
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

